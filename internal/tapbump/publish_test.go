// moduleRoot is the directory holding go.mod, found from this file's own
// path rather than from the working directory.
func moduleRoot(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller could not locate this test file")
	}
	root := filepath.Dir(filepath.Dir(filepath.Dir(file))) // internal/tapbump -> internal -> root
	if _, err := os.Stat(filepath.Join(root, "go.mod")); err != nil {
		t.Fatalf("no go.mod at the computed module root %s: %v", root, err)
	}
	return root
}

func gitTool(t *testing.T) string {
	t.Helper()
	path, err := exec.LookPath("git")
	if err != nil {
		t.Skipf("no git on PATH: %v", err)
	}
	return path
}

func goTool(t *testing.T) string {
	t.Helper()
	path, err := exec.LookPath("go")
	if err != nil {
		t.Skipf("no go toolchain on PATH: %v", err)
	}
	return path
}

func run(t *testing.T, dir string, name string, args ...string) string {
	t.Helper()
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	cmd.Env = sanitizedGitEnv()
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("%s %s (in %s): %v\n%s", name, strings.Join(args, " "), dir, err, out)
	}
	return string(out)
}

// sanitizedGitEnv is os.Environ() with every GIT_* variable stripped.
//
// This test invokes git against throwaway fixtures (a bare repo and its
// clones under t.TempDir()), always by an explicit cmd.Dir — but `git
// commit` exports GIT_DIR (and friends) into hooks/pre-commit's own process
// tree while a commit is in flight, and that inherits straight through `go
// test` into every exec.Command this file runs. GIT_DIR overrides cmd.Dir
// outright, so a fixture "commit" silently lands in THIS repository's real
// index instead of the fixture's. Observed directly: running this suite
// under `git commit` (hooks/pre-commit's `go test ./...`) staged this
// package's own seeded Formula/kazi.rb fixture into dira's own working
// tree, and the fixture's own commit then failed because git was pointed at
// the wrong git-dir/work-tree pair. Every git invocation in this file must
// run with a clean environment, not just an explicit cmd.Dir.
func sanitizedGitEnv() []string {
	env := os.Environ()
	out := env[:0:0]
	for _, e := range env {
		if strings.HasPrefix(e, "GIT_") {
			continue
		}
		out = append(out, e)
	}
	return out
}

const seededKaziFormula = `# Generated by the kazi release pipeline (ADR-0017). Do not hand-edit.
class Kazi < Formula
  desc "Reconciliation controller"
  homepage "https://github.com/kazi-org/kazi"
  version "1.275.1"
  license "Apache-2.0"
end
`

// newFixtureTap creates a local bare git repository seeded with an arbitrary
// Formula/kazi.rb, standing in for kazi-org/homebrew-tap — this test suite
// never touches a real one. Returns the bare repo's path (usable as a git
// remote via a plain filesystem path) and the seeded kazi.rb bytes.
func newFixtureTap(t *testing.T) (bareRepo string, kaziBytes []byte) {
	t.Helper()
	git := gitTool(t)
	dir := t.TempDir()
	bareRepo = filepath.Join(dir, "homebrew-tap.git")
	run(t, dir, git, "init", "--quiet", "--bare", "-b", "main", bareRepo)

	seed := filepath.Join(dir, "seed")
	run(t, dir, git, "clone", "--quiet", bareRepo, seed)
	if err := os.MkdirAll(filepath.Join(seed, "Formula"), 0o755); err != nil {
		t.Fatal(err)
	}
	kaziBytes = []byte(seededKaziFormula)
	if err := os.WriteFile(filepath.Join(seed, "Formula", "kazi.rb"), kaziBytes, 0o644); err != nil {
		t.Fatal(err)
	}
	run(t, seed, git, "add", "Formula/kazi.rb")
	run(t, seed, git, "-c", "user.name=fixture", "-c", "user.email=fixture@example.com",
		"commit", "--quiet", "-m", "seed: Formula/kazi.rb")
	run(t, seed, git, "push", "--quiet", "origin", "HEAD:refs/heads/main")
	return bareRepo, kaziBytes
}

// fixtureInputs is the version and per-target url/sha256 pair every test in
